    public function store(Request $request)
    {
        // Validar la entrada
        $request->validate([
            'temperatura' => 'required|numeric',
        ]);

        // Crear una nueva instancia del modelo y guardar el dato
        $valor = new Valor();
        $valor->temperatura = $request->input('temperatura');
        $valor->save();

        return redirect('/insertando_valores')->with('success', 'Valor insertado exitosamente');
